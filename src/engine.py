"""
Delta Guardian: Heuristic Decision Engine
Evaluates Delta Lake table metrics against lakehouse best practices to compute
a health score (0-100), identify storage inefficiencies, and generate automated
maintenance flags for compaction (OPTIMIZE) and dead file cleanup (VACUUM).
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional

from src.inspector import TableMetrics, format_bytes


class Severity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


class HealthGrade(str, Enum):
    EXCELLENT = "EXCELLENT"  # 90-100
    GOOD = "GOOD"            # 75-89
    WARNING = "WARNING"      # 50-74
    CRITICAL = "CRITICAL"    # 0-49


@dataclass
class Recommendation:
    """A specific maintenance or optimization action suggested by the engine."""
    action: str              # e.g., 'OPTIMIZE', 'VACUUM', 'CHECKPOINT'
    severity: Severity
    title: str
    description: str
    suggested_command: str
    estimated_impact: str


@dataclass
class PenaltyDetail:
    """Breakdown of points deducted from table health score."""
    rule_name: str
    points_deducted: float
    reason: str
    severity: Severity


@dataclass
class CostAndPerformanceImpact:
    """Estimated cost and query latency impact of current table health."""
    estimated_file_reduction_pct: float
    reclaimable_storage_bytes: int
    formatted_reclaimable_storage: str
    estimated_api_call_reduction_ratio: str
    query_planning_impact: str
    object_store_iops_impact: str


@dataclass
class HealthReport:
    """Comprehensive health assessment generated by the heuristic engine."""
    score: int
    grade: HealthGrade
    requires_optimize: bool
    requires_vacuum: bool
    penalties: List[PenaltyDetail]
    optimize_reasons: List[str]
    vacuum_reasons: List[str]
    recommendations: List[Recommendation]
    impact: CostAndPerformanceImpact
    metrics: TableMetrics

    def to_dict(self) -> Dict[str, Any]:
        """Convert report to a JSON-serializable dictionary."""
        return {
            "score": self.score,
            "grade": self.grade.value,
            "requires_optimize": self.requires_optimize,
            "requires_vacuum": self.requires_vacuum,
            "penalties": [
                {
                    "rule": p.rule_name,
                    "points": p.points_deducted,
                    "reason": p.reason,
                    "severity": p.severity.value,
                }
                for p in self.penalties
            ],
            "optimize_reasons": self.optimize_reasons,
            "vacuum_reasons": self.vacuum_reasons,
            "recommendations": [
                {
                    "action": r.action,
                    "severity": r.severity.value,
                    "title": r.title,
                    "description": r.description,
                    "command": r.suggested_command,
                    "impact": r.estimated_impact,
                }
                for r in self.recommendations
            ],
            "impact": {
                "estimated_file_reduction_pct": self.impact.estimated_file_reduction_pct,
                "reclaimable_storage_bytes": self.impact.reclaimable_storage_bytes,
                "formatted_reclaimable_storage": self.impact.formatted_reclaimable_storage,
                "api_call_reduction": self.impact.estimated_api_call_reduction_ratio,
                "query_planning": self.impact.query_planning_impact,
                "object_store_iops": self.impact.object_store_iops_impact,
            },
            "metrics": self.metrics.to_dict(),
        }


class HeuristicEngine:
    """Configurable heuristics engine for evaluating Delta Lake table health."""

    def __init__(
        self,
        small_file_threshold_pct: float = 30.0,
        tiny_file_threshold_pct: float = 15.0,
        tombstone_ratio_threshold_pct: float = 15.0,
        min_tombstone_count_trigger: int = 5,
        target_file_size_mb: float = 128.0,
    ) -> None:
        self.small_file_threshold_pct = small_file_threshold_pct
        self.tiny_file_threshold_pct = tiny_file_threshold_pct
        self.tombstone_ratio_threshold_pct = tombstone_ratio_threshold_pct
        self.min_tombstone_count_trigger = min_tombstone_count_trigger
        self.target_file_size_bytes = int(target_file_size_mb * 1024 * 1024)

    def evaluate(self, metrics: TableMetrics) -> HealthReport:
        """Evaluates metrics against threshold rules and returns a HealthReport."""
        if not metrics.is_valid_delta_table:
            return HealthReport(
                score=0,
                grade=HealthGrade.CRITICAL,
                requires_optimize=False,
                requires_vacuum=False,
                penalties=[
                    PenaltyDetail(
                        rule_name="InvalidTable",
                        points_deducted=100.0,
                        reason="Directory is not a valid Delta Lake table (no _delta_log found)",
                        severity=Severity.CRITICAL,
                    )
                ],
                optimize_reasons=[],
                vacuum_reasons=[],
                recommendations=[
                    Recommendation(
                        action="GENERATE",
                        severity=Severity.CRITICAL,
                        title="Initialize Delta Table",
                        description="Run 'python main.py generate' to create a test table.",
                        suggested_command="python main.py generate",
                        estimated_impact="Sets up a managed Delta Lake table structure.",
                    )
                ],
                impact=CostAndPerformanceImpact(
                    estimated_file_reduction_pct=0.0,
                    reclaimable_storage_bytes=0,
                    formatted_reclaimable_storage="0 B",
                    estimated_api_call_reduction_ratio="1x",
                    query_planning_impact="N/A",
                    object_store_iops_impact="N/A",
                ),
                metrics=metrics,
            )

        penalties: List[PenaltyDetail] = []
        optimize_reasons: List[str] = []
        vacuum_reasons: List[str] = []
        recommendations: List[Recommendation] = []

        requires_optimize = False
        requires_vacuum = False

        # Rule 1: Small File Ratio (< 16MB)
        # Max penalty: 35 points
        if metrics.active_file_count > 1 and metrics.small_file_pct > self.small_file_threshold_pct:
            requires_optimize = True
            ratio_above = (metrics.small_file_pct - self.small_file_threshold_pct) / (100.0 - self.small_file_threshold_pct)
            deduction = round(15.0 + (ratio_above * 20.0), 1)
            severity = Severity.CRITICAL if metrics.small_file_pct > 75.0 else Severity.WARNING
            msg = (
                f"{metrics.small_file_pct:.1f}% of active files are smaller than 16MB "
                f"(threshold: {self.small_file_threshold_pct:.1f}%). "
                f"Severely impairs Parquet dictionary encoding and columnar reader throughput."
            )
            penalties.append(PenaltyDetail("SmallFileRatio", deduction, msg, severity))
            optimize_reasons.append(msg)

        # Rule 2: Extreme Tiny Files (< 1MB)
        # Files < 1MB are catastrophic for lakehouse read planning and S3/ADLS IOPS.
        # Max penalty: 25 points
        if metrics.active_file_count > 1 and metrics.tiny_file_pct > self.tiny_file_threshold_pct:
            requires_optimize = True
            deduction = round(min(25.0, (metrics.tiny_file_pct / 100.0) * 25.0), 1)
            severity = Severity.CRITICAL if metrics.tiny_file_pct > 60.0 else Severity.WARNING
            msg = (
                f"{metrics.tiny_file_pct:.1f}% of active files are tiny (< 1MB). "
                f"Creates severe HTTP GET request amplification and cloud object store throttling."
            )
            penalties.append(PenaltyDetail("TinyFilesSeverity", deduction, msg, severity))
            optimize_reasons.append(msg)

        # Rule 3: File Volume Imbalance / Fragmentation Index
        # Max penalty: 15 points
        ideal_files = max(1, math.ceil(metrics.active_total_bytes / self.target_file_size_bytes))
        fragmentation_ratio = metrics.active_file_count / ideal_files if ideal_files > 0 else 1.0

        if metrics.active_file_count > 10 and fragmentation_ratio > 5.0:
            requires_optimize = True
            deduction = round(min(15.0, math.log2(fragmentation_ratio) * 3.0), 1)
            msg = (
                f"High fragmentation index: Table has {metrics.active_file_count} files "
                f"for {format_bytes(metrics.active_total_bytes)} of data "
                f"(ideal target: ~{ideal_files} file(s) at 128MB each, fragmentation: {fragmentation_ratio:.1f}x)."
            )
            penalties.append(PenaltyDetail("VolumeImbalance", deduction, msg, Severity.WARNING))
            optimize_reasons.append(msg)

        # Rule 4: Tombstone & Dead File Accumulation (VACUUM Trigger)
        # Max penalty: 25 points
        if (
            metrics.tombstoned_files_on_disk_count >= self.min_tombstone_count_trigger
            and metrics.tombstoned_ratio_pct > self.tombstone_ratio_threshold_pct
        ):
            requires_vacuum = True
            deduction = round(min(25.0, (metrics.tombstoned_ratio_pct / 100.0) * 30.0), 1)
            severity = Severity.CRITICAL if metrics.tombstoned_ratio_pct > 40.0 else Severity.WARNING
            msg = (
                f"{metrics.tombstoned_files_on_disk_count} unreferenced historical files on disk "
                f"consuming {format_bytes(metrics.tombstoned_files_on_disk_bytes)} "
                f"({metrics.tombstoned_ratio_pct:.1f}% of total table storage). Requires VACUUM."
            )
            penalties.append(PenaltyDetail("TombstoneAccumulation", deduction, msg, severity))
            vacuum_reasons.append(msg)

        elif metrics.tombstoned_files_on_disk_count > 0:
            # Minor tombstone presence: note it but don't heavily penalize
            msg = (
                f"{metrics.tombstoned_files_on_disk_count} tombstoned files detected on disk "
                f"({format_bytes(metrics.tombstoned_files_on_disk_bytes)})."
            )
            vacuum_reasons.append(msg)
            if metrics.tombstoned_files_on_disk_count >= 10:
                requires_vacuum = True

        # Calculate Final Score
        total_penalty = sum(p.points_deducted for p in penalties)
        final_score = max(0, min(100, round(100.0 - total_penalty)))

        if final_score >= 90:
            grade = HealthGrade.EXCELLENT
        elif final_score >= 75:
            grade = HealthGrade.GOOD
        elif final_score >= 50:
            grade = HealthGrade.WARNING
        else:
            grade = HealthGrade.CRITICAL

        # Generate Actionable Recommendations
        if requires_optimize:
            reduction_files = max(0, metrics.active_file_count - ideal_files)
            reduction_pct = (
                (reduction_files / metrics.active_file_count * 100.0)
                if metrics.active_file_count > 0
                else 0.0
            )
            recommendations.append(
                Recommendation(
                    action="OPTIMIZE",
                    severity=Severity.CRITICAL if grade == HealthGrade.CRITICAL else Severity.WARNING,
                    title="Compact Small Parquet Files",
                    description=(
                        f"Run Delta compaction to coalesce {metrics.active_file_count} small files "
                        f"into ~{ideal_files} bin-packed Parquet files."
                    ),
                    suggested_command="python main.py optimize --compact",
                    estimated_impact=(
                        f"Reduces file count by ~{reduction_pct:.1f}% ({metrics.active_file_count} -> {ideal_files}). "
                        f"Speeds up scan queries by 3x-10x and eliminates S3/ADLS IOPS throttling."
                    ),
                )
            )

        if requires_vacuum:
            recommendations.append(
                Recommendation(
                    action="VACUUM",
                    severity=Severity.WARNING if metrics.tombstoned_ratio_pct < 40 else Severity.CRITICAL,
                    title="Prune Unreferenced Tombstoned Files",
                    description=(
                        f"Execute VACUUM to permanently remove {metrics.tombstoned_files_on_disk_count} dead files "
                        f"older than retention threshold."
                    ),
                    suggested_command="python main.py optimize --vacuum --retention-hours 0",
                    estimated_impact=(
                        f"Instantly reclaims {format_bytes(metrics.tombstoned_files_on_disk_bytes)} of wasted storage "
                        f"and cleans transaction log metadata overhead."
                    ),
                )
            )

        if not requires_optimize and not requires_vacuum:
            recommendations.append(
                Recommendation(
                    action="MAINTAIN",
                    severity=Severity.INFO,
                    title="Table Storage Healthy",
                    description="No urgent compaction or vacuum required. Current file distribution is optimal.",
                    suggested_command="python main.py scan",
                    estimated_impact="Table is running at peak query efficiency.",
                )
            )

        # Estimate Cost and Performance Impact
        reduction_pct = 0.0
        if metrics.active_file_count > ideal_files:
            reduction_pct = ((metrics.active_file_count - ideal_files) / metrics.active_file_count) * 100.0

        api_reduction_ratio = f"{max(1, metrics.active_file_count // max(1, ideal_files))}x"
        
        if metrics.tiny_file_pct > 50.0:
            query_impact = "SEVERE DEGRADATION: Extreme footer parsing overhead & metadata bloat"
            iops_impact = "HIGH OVERHEAD: Excessive cloud object store GET/LIST requests"
        elif metrics.small_file_pct > 30.0:
            query_impact = "MODERATE DEGRADATION: Sub-optimal column vectorization"
            iops_impact = "ELEVATED: Redundant metadata reads per query"
        else:
            query_impact = "OPTIMAL: Full vectorized columnar read performance"
            iops_impact = "MINIMAL: Near 1:1 request-to-data efficiency"

        impact = CostAndPerformanceImpact(
            estimated_file_reduction_pct=round(reduction_pct, 1),
            reclaimable_storage_bytes=metrics.tombstoned_files_on_disk_bytes,
            formatted_reclaimable_storage=format_bytes(metrics.tombstoned_files_on_disk_bytes),
            estimated_api_call_reduction_ratio=api_reduction_ratio,
            query_planning_impact=query_impact,
            object_store_iops_impact=iops_impact,
        )

        return HealthReport(
            score=final_score,
            grade=grade,
            requires_optimize=requires_optimize,
            requires_vacuum=requires_vacuum,
            penalties=penalties,
            optimize_reasons=optimize_reasons,
            vacuum_reasons=vacuum_reasons,
            recommendations=recommendations,
            impact=impact,
            metrics=metrics,
        )


